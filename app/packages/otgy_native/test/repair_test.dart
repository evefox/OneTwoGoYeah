Uint8List _malformedRecovery() {
  final digits = _malformedRecoveryHex;
  final bytes = Uint8List(digits.length ~/ 2);
  for (var index = 0; index < bytes.length; index++) {
    bytes[index] = int.parse(
      digits.substring(index * 2, index * 2 + 2),
      radix: 16,
    );
  }
  return bytes;
}

void main() {
  test('load repair rebuilds visible moves and reports the change', () {
    final payload = _malformedRecovery();
    final decoded = NativeChartEditor.decodeRecoveryWithRepair(payload);
    addTearDown(decoded.editor.dispose);

    expect(decoded.repaired, isTrue);
    final repairedPayload = decoded.editor.encodeRecovery();
    expect(repairedPayload, isNot(payload));

    final again = NativeChartEditor.decodeRecoveryWithRepair(repairedPayload);
    addTearDown(again.editor.dispose);
    expect(again.repaired, isFalse);
  });

  test('exact recovery decode remains byte preserving', () {
    final payload = _malformedRecovery();
    final editor = NativeChartEditor.decodeRecovery(payload);
    addTearDown(editor.dispose);
    expect(editor.encodeRecovery(), payload);
  });
}
