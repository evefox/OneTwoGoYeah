Uint8List _malformedFormal() {
  final bytes = Uint8List(_malformedFormalHex.length ~/ 2);
  for (var index = 0; index < bytes.length; index++) {
    bytes[index] = int.parse(
      _malformedFormalHex.substring(index * 2, index * 2 + 2),
      radix: 16,
    );
  }
  return bytes;
}

Uint8List _malformedRecovery() {
  final bytes = Uint8List(_malformedRecoveryHex.length ~/ 2);
  for (var index = 0; index < bytes.length; index++) {
    bytes[index] = int.parse(
      _malformedRecoveryHex.substring(index * 2, index * 2 + 2),
      radix: 16,
    );
  }
  return bytes;
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  late Directory directory;
  late LocalProjectStore store;
  late EditorController controller;

  setUp(() async {
    directory = await Directory.systemTemp.createTemp('otgy-repair-');
    store = await LocalProjectStore.openAt(directory);
    controller = EditorController();
  });

  tearDown(() async {
    controller.dispose();
    if (await directory.exists()) {
      await directory.delete(recursive: true);
    }
  });

  test(
    'loading a malformed draft repairs and persists it immediately',
    () async {
      final original = _malformedFormal();
      await store.saveDraft(id: 'broken', name: 'broken', payload: original);

      final repaired = controller.loadFormalDraft(
        payload: original,
        draftId: 'broken',
        draftName: 'broken',
      );
      expect(repaired, isTrue);
      expect(controller.isDirty, isTrue);

      final repairedPayload = controller.encodeFormalDraft();
      expect(repairedPayload, isNot(orderedEquals(original)));
      await store.saveDraft(
        id: 'broken',
        name: 'broken',
        payload: repairedPayload,
      );
      controller.markSaved(
        draftId: 'broken',
        draftName: 'broken',
        payload: repairedPayload,
      );
      expect(controller.isDirty, isFalse);

      final stored = await store.listDrafts();
      expect(stored, hasLength(1));
      expect(stored.single.payload, orderedEquals(repairedPayload));

      final reload = EditorController();
      addTearDown(reload.dispose);
      expect(
        reload.loadFormalDraft(
          payload: stored.single.payload,
          draftId: 'broken',
          draftName: 'broken',
        ),
        isFalse,
      );
    },
  );

  test('recovery repair overwrites the recovery record immediately', () async {
    final original = _malformedRecovery();
    final repaired = controller.restoreRecovery(original);
    expect(repaired, isTrue);

    final repairedPayload = controller.encodeRecoverySnapshot();
    expect(repairedPayload, isNot(orderedEquals(original)));
    await store.writeRecovery(repairedPayload);

    final stored = await store.readRecovery();
    expect(stored, isNotNull);
    expect(stored, orderedEquals(repairedPayload));

    final reload = EditorController();
    addTearDown(reload.dispose);
    expect(reload.restoreRecovery(stored!), isFalse);
  });
}
