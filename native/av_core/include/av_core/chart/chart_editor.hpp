namespace otgy::core {

enum class ChartEditCode : std::uint8_t {
  Success = 0,
  NoChange = 1,
  PositionOccupied = 2,
  CannotAppendAfterEnd = 3,
  CannotPlace = 4,
  NoNpcSource = 5,
  GenerationRangeOccupied = 6,
  AutoGeneratedMarkerLocked = 7,
  InvalidShowtimePosition = 8,
  NoRemainingDanceMoves = 9,
  ShowtimeRangeOccupied = 10,
  InvalidDraft = 11,
  RangeOverflow = 12,
  IdExhausted = 13,
  AllocationFailure = 14,
  NothingToUndo = 15,
  NothingToRedo = 16,
  SelectionUnavailable = 17,
  ClipboardEmpty = 18,
  PasteRangeOccupied = 19,
  ShowtimeContentStale = 20,
  CutSourceChanged = 21,
};

[[nodiscard]] constexpr std::string_view chart_edit_code_message(
    ChartEditCode code) noexcept {
  switch (code) {
    case ChartEditCode::Success:
      return {};
    case ChartEditCode::NoChange:
      return "chart edit made no change";
    case ChartEditCode::PositionOccupied:
      return "chart row is already occupied";
    case ChartEditCode::CannotAppendAfterEnd:
      return "cannot append after a move end marker";
    case ChartEditCode::CannotPlace:
      return "marker cannot be placed in this context";
    case ChartEditCode::NoNpcSource:
      return "no NPC demonstration is available to copy";
    case ChartEditCode::GenerationRangeOccupied:
      return "generated marker range is occupied";
    case ChartEditCode::AutoGeneratedMarkerLocked:
      return "automatically generated player marker cannot be edited";
    case ChartEditCode::InvalidShowtimePosition:
      return "Showtime move position is invalid";
    case ChartEditCode::NoRemainingDanceMoves:
      return "no remaining dance moves are available";
    case ChartEditCode::ShowtimeRangeOccupied:
      return "Showtime display range is occupied";
    case ChartEditCode::InvalidDraft:
      return "chart draft cannot be edited because its identity or relation data is invalid";
    case ChartEditCode::RangeOverflow:
      return "chart edit exceeds the row limit";
    case ChartEditCode::IdExhausted:
      return "chart object identifiers are exhausted";
    case ChartEditCode::AllocationFailure:
      return "unable to allocate chart edit state";
    case ChartEditCode::NothingToUndo:
      return "there is no chart edit to undo";
    case ChartEditCode::NothingToRedo:
      return "there is no chart edit to redo";
    case ChartEditCode::SelectionUnavailable:
      return "no selectable dance move is available";
    case ChartEditCode::ClipboardEmpty:
      return "the chart clipboard is empty";
    case ChartEditCode::PasteRangeOccupied:
      return "pasted dance move range is occupied";
    case ChartEditCode::ShowtimeContentStale:
      return "the Showtime content no longer matches its dance moves";
    case ChartEditCode::CutSourceChanged:
      return "the pending cut source has changed";
  }
  return "unknown chart edit result";
}

struct ChartEditResult final {
  ChartEditCode code;
  bool changed;
  ChartEventId primary_event_id;

  [[nodiscard]] explicit operator bool() const noexcept {
    return code == ChartEditCode::Success;
  }
};

/// The dance move selected in the current editor session. The row span is
/// derived from the draft and covers every NPC and player event bound to the
/// drill, so it stays correct for a draft that is still incomplete.
struct ChartSelection final {
  bool active{false};
  ChartDanceMoveDrillId drill_id{0U};
  std::uint64_t first_row{0U};
  std::uint64_t last_row{0U};
};

/// Independent session snapshot of all selected dance moves. Rows are offsets
/// from their shared smallest source row, preserving gaps between moves. The
/// three Showtime vectors are empty. Never persisted or sent to a platform
/// clipboard.
struct ChartClipboardFragment final {
  std::uint64_t base_row{0U};
  ChartDraft content{{}, {}, {}, {}, {}, {}};
};

/// Result of a command that only changes session state. `changed` describes the
/// selection or clipboard and never the draft: session commands produce no
/// history entry.
struct ChartSessionResult final {
  ChartEditCode code;
  bool changed;

  [[nodiscard]] explicit operator bool() const noexcept {
    return code == ChartEditCode::Success;
  }
};

/// Read-only paste assessment. Spans and ghost IDs refer to clipboard objects,
/// never newly allocated chart objects. Representable geometry is returned even
/// for an occupied destination or a changed cut source.
struct ChartPastePreview final {
  ChartEditCode code{ChartEditCode::ClipboardEmpty};
  std::uint64_t anchor_row{0U};
  std::uint64_t last_row{0U};
  std::vector<ChartSelection> spans;
  std::vector<ChartMarker> ghost_markers;

  [[nodiscard]] explicit operator bool() const noexcept {
    return code == ChartEditCode::Success;
  }
};

/// Owns the current ChartDraft and snapshot history. Each successful context
/// click, multi-event generation or deletion is one atomic history entry.
class ChartEditor final {
 public:
  explicit ChartEditor(ChartDraft draft) noexcept;

  [[nodiscard]] const ChartDraft& draft() const noexcept { return draft_; }
  [[nodiscard]] bool can_undo() const noexcept { return !undo_.empty(); }
  [[nodiscard]] bool can_redo() const noexcept { return !redo_.empty(); }
  [[nodiscard]] std::size_t undo_count() const noexcept { return undo_.size(); }
  [[nodiscard]] std::size_t redo_count() const noexcept { return redo_.size(); }
  [[nodiscard]] const std::vector<ChartSelection>& selections() const noexcept {
    return selections_;
  }
  [[nodiscard]] bool has_pending_cut() const noexcept { return pending_cut_; }
  [[nodiscard]] const ChartClipboardFragment& clipboard() const noexcept {
    return clipboard_;
  }
  [[nodiscard]] bool has_clipboard() const noexcept { return has_clipboard_; }

  [[nodiscard]] ChartEditResult click(ChartColumn column,
                                      std::uint64_t row) noexcept;
  [[nodiscard]] ChartEditResult clear() noexcept;
  [[nodiscard]] ChartEditResult undo() noexcept;
  [[nodiscard]] ChartEditResult redo() noexcept;

  /// Session commands. They never touch the draft and never add history.
  [[nodiscard]] ChartSessionResult select(ChartColumn column,
                                          std::uint64_t row) noexcept;
  [[nodiscard]] ChartSessionResult clear_selection() noexcept;
  [[nodiscard]] ChartSessionResult copy_selection() noexcept;
  [[nodiscard]] ChartSessionResult clear_clipboard() noexcept;

  /// Prepares a pending cut without changing the draft or its history. The first
  /// successful paste verifies and removes all sources in the same transaction
  /// as insertion, then turns the clipboard into an ordinary copy. Undo never
  /// restores pending-cut state. `changed` here describes session state only.
  [[nodiscard]] ChartSessionResult cut_selection() noexcept;

  /// Toggles the drill at an exact marker row from any valid chart column;
  /// empty rows and unselectable markers retain the set.
  [[nodiscard]] ChartSessionResult toggle_selection(ChartColumn column,
                                                   std::uint64_t row) noexcept {
    return select(column, row);
  }
  [[nodiscard]] ChartPastePreview preview_paste(
      std::uint64_t anchor_row) const noexcept;

  /// Translates all clipboard content in one history entry. The smallest source
  /// row is anchored on anchor_row; roles, columns and relative gaps survive.
  [[nodiscard]] ChartEditResult paste(std::uint64_t anchor_row) noexcept;

 private:
  [[nodiscard]] ChartEditResult commit(ChartDraft draft,
                                       ChartEditResult result,
                                       std::uint64_t next_id,
                                       bool id_available) noexcept;

  [[nodiscard]] ChartSessionResult prepare_clipboard(bool cut) noexcept;

  /// Re-derives each selected span and drops only members with no bound event.
  /// Allocates nothing, including when called after history navigation.
  void revalidate_selection() noexcept;

  ChartDraft draft_;
  std::vector<ChartDraft> undo_;
  std::vector<ChartDraft> redo_;
  std::uint64_t next_id_;
  bool id_available_;
  std::vector<ChartSelection> selections_;
  ChartClipboardFragment clipboard_{};
  ChartDraft cut_source_{{}, {}, {}, {}, {}, {}};
  bool has_clipboard_{false};
  bool pending_cut_{false};
};

}  // namespace otgy::core
